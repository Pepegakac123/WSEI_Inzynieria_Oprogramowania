from adgen import Activity

K, S, B = "Klient", "System", "Bramka płatności"
d = Activity([K, S, B], lane_w=380, height=1600, top=120,
             title="Diagram aktywności: rezerwacja wizyty")
x0, x1, x2 = d.lx(K), d.lx(S), d.lx(B)
LOOP = x1 + 165  # pionowa linia powrotu po prawej stronie toru System

d.start("start", K, 160)
d.action("salon", K, 230, "Wybierz salon i usługę")
d.action("prac", K, 320, "Wybierz pracownika\nlub „dowolny dostępny”")
d.action("terminy", S, 320, "Pokaż wolne terminy\nna 14 dni")
d.decision("sa_wolne", S, 420, "są wolne\nterminy?")
d.action("lista", K, 420, "Zapisz się na listę\noczekujących", improved=True)
d.end("koniec_lista", K, 510, label="czeka na ofertę terminu")
d.action("wybor", K, 600, "Wybierz termin")
d.action("zasady", S, 690, "Pokaż zasady odwołania\ni wymaganą płatność")
d.decision("potwierdza", K, 780, "potwierdza?", side="right")
d.end("koniec_rezygnacja", K, 780, dx=-125, label="wizyta\nnie powstaje")
d.decision("nadal_wolny", S, 870, "termin nadal wolny?", side="top")
d.decision("zadatek", S, 960, "salon wymaga\nzadatku?", side="left")
d.action("pobierz", B, 960, "Pobierz zadatek")
d.decision("udana", B, 1060, "płatność\nudana?", side="right")
d.end("koniec_platnosc", B, 1160, label="wizyta nie powstaje,\nmożna spróbować ponownie")
d.decision("scal", S, 1060)
d.action("utworz", S, 1150, "Utwórz wizytę")
d.action("potw", S, 1240, "Wyślij potwierdzenie")
d.action("bede", S, 1330, "Zaplanuj prośbę „Będę”\nna 24 h przed wizytą", improved=True)
d.end("koniec", S, 1430, label="wizyta zarezerwowana")

d.flow("start", "salon")
d.flow("salon", "prac")
d.flow("prac", "terminy")
d.flow("terminy", "sa_wolne")
d.flow("sa_wolne", "lista", guard="[nie]", gdx=-60, gdy=-8)
d.flow("lista", "koniec_lista")
d.flow("sa_wolne", "wybor", via=[(x1, 600)], guard="[tak]", gdx=24, gdy=40, anchor="start")
d.flow("wybor", "zasady", via=[(x0, 690)])
d.flow("zasady", "potwierdza", via=[(x1, 780)])
d.flow("potwierdza", "koniec_rezygnacja", guard="[nie]", gdx=-58, gdy=-8)
d.flow("potwierdza", "nadal_wolny", via=[(x0, 870)], guard="[tak]", gdx=10, gdy=48, anchor="start")
d.flow("nadal_wolny", "terminy", via=[(LOOP, 870), (LOOP, 320)],
       guard="[nie, ktoś go zajął]", guard_at=0, gdx=6, gdy=26, anchor="start")
d.flow("nadal_wolny", "zadatek", guard="[tak]", gdx=10, gdy=40, anchor="start")
d.flow("zadatek", "pobierz", guard="[tak]", gdx=70, gdy=-8)
d.flow("zadatek", "scal", guard="[nie]", gdx=10, gdy=42, anchor="start")
d.flow("pobierz", "udana")
d.flow("udana", "scal", guard="[tak]", gdx=-70, gdy=-8)
d.flow("udana", "koniec_platnosc", guard="[nie]", gdx=10, gdy=44, anchor="start")
d.flow("scal", "utworz")
d.flow("utworz", "potw")
d.flow("potw", "bede")
d.flow("bede", "koniec")

d.activity_legend(20, 1555)
d.save_png("ad_1_rezerwacja.png")
