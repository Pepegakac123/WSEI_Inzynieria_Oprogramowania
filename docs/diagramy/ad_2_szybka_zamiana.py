from adgen import Activity

K, S, O, B = "Klient odwołujący", "System", "Osoba z listy", "Bramka płatności"
d = Activity([K, S, O, B], lane_w=350, height=1990, top=120,
             title="Diagram aktywności: odwołanie wizyty i Szybka Zamiana")
xk, xs, xo, xb = d.lx(K), d.lx(S), d.lx(O), d.lx(B)

d.start("start", K, 160)
d.action("odwolaj", K, 230, "Odwołaj wizytę")
d.action("czas", S, 230, "Sprawdź czas\ndarmowego odwołania")
d.action("skutki", S, 330, "Pokaż skutki: zwrot,\nkupon albo utrata zadatku", improved=True)
d.decision("potwierdza", K, 420, "potwierdza?")
d.end("koniec_bez_zmian", K, 420, dx=-115, label="wizyta\nbez zmian")
d.decision("darmowe", S, 510, "w darmowym\nczasie?", side="left")
d.action("zwrot", B, 510, "Zwróć zadatek")
d.decision("scal1", S, 600)
d.action("zwolnij", S, 680, "Zwolnij termin")
d.decision("czeka", S, 780, "czy ktoś czeka?")
d.end("koniec_pula", S, 780, dx=-120, label="termin wraca\ndo puli wolnych")
d.action("wybierz", S, 940, "Wybierz pierwszą\npasującą osobę i zablokuj\ndla niej termin", improved=True)
d.action("oferta", S, 1060, "Wyślij ofertę: 15 min\nna decyzję (5 min, gdy\ndo wizyty < 6 h)", improved=True)
d.decision("odpowiedz", O, 1060, "odpowiedź\nna ofertę?")
d.action("przyjmij", O, 1170, "Przyjmij ofertę", improved=True)
d.action("pobierz", B, 1170, "Pobierz zadatek\n(jeśli salon wymaga)")
d.decision("udana", B, 1270, "płatność\nudana?")
d.action("utworz", S, 1360, "Utwórz wizytę nowej\nosoby i usuń ją z listy")
d.decision("po_czasie", S, 1460, "odwołanie\npo czasie?")
d.action("kupon", S, 1590, "Utwórz kupon dla\nodwołującego (3 mies.)", improved=True)
d.decision("scal2", S, 1680)
d.action("powiadom", S, 1760, "Powiadom pracownika\ni odwołującego")
d.end("koniec", S, 1850, label="termin przejęty")

d.flow("start", "odwolaj")
d.flow("odwolaj", "czas")
d.flow("czas", "skutki")
d.flow("skutki", "potwierdza", via=[(xs, 420)])
d.flow("potwierdza", "koniec_bez_zmian", guard="[nie]", gdx=-55, gdy=-8)
d.flow("potwierdza", "darmowe", via=[(xk, 510)], guard="[tak]", gdx=10, gdy=44, anchor="start")
d.flow("darmowe", "zwrot", guard="[tak]", gdx=70, gdy=-8)
d.flow("darmowe", "scal1", guard="[nie]", gdx=10, gdy=42, anchor="start")
d.flow("zwrot", "scal1", via=[(xb, 600)])
d.flow("scal1", "zwolnij")
d.flow("zwolnij", "czeka")
d.flow("czeka", "koniec_pula", guard="[nie]", gdx=-58, gdy=-8)
d.flow("czeka", "wybierz", guard="[tak]", gdx=10, gdy=40, anchor="start")
d.flow("wybierz", "oferta")
d.flow("oferta", "odpowiedz")
d.flow("odpowiedz", "czeka", via=[(xo, 780)],
       guard="[odrzuca / minął czas]", guard_at=0, gdx=-10, gdy=-60, anchor="end")
d.flow("odpowiedz", "przyjmij", guard="[przyjmuje]", gdx=10, gdy=44, anchor="start")
d.flow("przyjmij", "pobierz")
d.flow("pobierz", "udana")
d.flow("udana", "przyjmij", via=[(xo, 1270)], guard="[nie, oferta trwa]", gdx=-215, gdy=24, anchor="end")
d.flow("udana", "utworz", via=[(xb, 1360)], guard="[tak]", gdx=10, gdy=44, anchor="start")
d.flow("utworz", "po_czasie")
d.flow("po_czasie", "kupon", guard="[tak]", gdx=10, gdy=40, anchor="start")
d.flow("po_czasie", "scal2", via=[(xs - 125, 1460), (xs - 125, 1680)], guard="[nie]",
       gdx=-58, gdy=-8)
d.flow("kupon", "scal2")
d.flow("scal2", "powiadom")
d.flow("powiadom", "koniec")

d.activity_legend(20, 1945)
d.save_png("ad_2_szybka_zamiana.png")
